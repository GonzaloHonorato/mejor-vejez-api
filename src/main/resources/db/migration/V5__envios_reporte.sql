-- ---------------------------------------------------------------------
-- EJECUCION_PROCESO (V1): el reporte semanal es un tercer tipo de corrida
-- programada, junto a DETECCION_ATRASOS y ALERTAS_PREVENTIVAS.
-- ---------------------------------------------------------------------
ALTER TABLE EJECUCION_PROCESO DROP CONSTRAINT CK_EJECUCION_TIPO;

ALTER TABLE EJECUCION_PROCESO ADD CONSTRAINT CK_EJECUCION_TIPO
  CHECK (TIPO_EJECUCION IN ('GENERACION_TAREAS','DETECCION_ATRASOS','ALERTAS_PREVENTIVAS','REPORTE_SEMANAL'));

-- ---------------------------------------------------------------------
-- Envío del reporte semanal
-- ---------------------------------------------------------------------

-- Una fila por grupo y período (lunes de inicio): UQ_ENVIO_REPORTE_GRUPO_PERIODO
-- es la clave de idempotencia de POST /api/interno/reportes/envios.
CREATE TABLE ENVIO_REPORTE (
  ID_ENVIO             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_GRUPO             NUMBER NOT NULL,
  INICIO_PERIODO       DATE NOT NULL,
  FIN_PERIODO          DATE NOT NULL,
  ID_ESTADO            NUMBER NOT NULL,
  INTENTOS             NUMBER(3) DEFAULT 0 NOT NULL,
  FECHA_CREACION       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  FECHA_ACTUALIZACION  TIMESTAMP WITH TIME ZONE,
  DETALLE_ERROR        VARCHAR2(500),
  CONSTRAINT UQ_ENVIO_REPORTE_GRUPO_PERIODO UNIQUE (ID_GRUPO, INICIO_PERIODO),
  CONSTRAINT FK_ENVIO_REPORTE_GRUPO FOREIGN KEY (ID_GRUPO) REFERENCES GRUPO_FAMILIAR(ID_GRUPO),
  CONSTRAINT FK_ENVIO_REPORTE_ESTADO FOREIGN KEY (ID_ESTADO) REFERENCES CATALOGO_ESTADOS(ID_ESTADO)
);

-- Resultado del envío a cada destinatario (foto tomada al crear ENVIO_REPORTE).
CREATE TABLE ENVIO_REPORTE_DESTINATARIO (
  ID_ENVIO_DESTINATARIO  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ENVIO               NUMBER NOT NULL,
  ID_USUARIO             NUMBER NOT NULL,
  ID_ESTADO              NUMBER NOT NULL,
  DETALLE_ERROR          VARCHAR2(500),
  FECHA_ACTUALIZACION    TIMESTAMP WITH TIME ZONE,
  CONSTRAINT UQ_ENVIO_REPORTE_DESTINATARIO UNIQUE (ID_ENVIO, ID_USUARIO),
  CONSTRAINT FK_ENVIO_DEST_ENVIO FOREIGN KEY (ID_ENVIO) REFERENCES ENVIO_REPORTE(ID_ENVIO),
  CONSTRAINT FK_ENVIO_DEST_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
  CONSTRAINT FK_ENVIO_DEST_ESTADO FOREIGN KEY (ID_ESTADO) REFERENCES CATALOGO_ESTADOS(ID_ESTADO)
);

-- ---------------------------------------------------------------------
-- Catálogo: mismo patrón de carga que V2__catalogos.sql (MERGE, sin borrar).
-- ---------------------------------------------------------------------
DECLARE
  PROCEDURE estado(p_tabla VARCHAR2, p_campo VARCHAR2, p_codigo VARCHAR2,
                   p_descripcion VARCHAR2, p_orden NUMBER) IS
  BEGIN
    MERGE INTO CATALOGO_ESTADOS c
    USING (SELECT p_tabla AS t, p_campo AS f, p_codigo AS k FROM DUAL) s
       ON (c.NOMBRE_TABLA = s.t AND c.NOMBRE_CAMPO = s.f AND c.CODIGO_ESTADO = s.k)
     WHEN MATCHED THEN UPDATE SET c.DESCRIPCION = p_descripcion, c.ORDEN = p_orden
     WHEN NOT MATCHED THEN INSERT (NOMBRE_TABLA, NOMBRE_CAMPO, CODIGO_ESTADO, DESCRIPCION, ORDEN)
                           VALUES (p_tabla, p_campo, p_codigo, p_descripcion, p_orden);
  END;
BEGIN
  estado('ENVIO_REPORTE', 'ESTADO', 'PENDIENTE', 'Pendiente', 1);
  estado('ENVIO_REPORTE', 'ESTADO', 'ENVIADO',   'Enviado',   2);
  estado('ENVIO_REPORTE', 'ESTADO', 'FALLIDO',   'Fallido',   3);

  estado('ENVIO_REPORTE_DESTINATARIO', 'ESTADO', 'PENDIENTE', 'Pendiente', 1);
  estado('ENVIO_REPORTE_DESTINATARIO', 'ESTADO', 'ENVIADO',   'Enviado',   2);
  estado('ENVIO_REPORTE_DESTINATARIO', 'ESTADO', 'FALLIDO',   'Fallido',   3);

  COMMIT;
END;
/

-- ---------------------------------------------------------------------
-- Comentarios de documentación
-- ---------------------------------------------------------------------
COMMENT ON TABLE ENVIO_REPORTE IS 'Registro idempotente (ID_GRUPO, INICIO_PERIODO) del envío del reporte PDF semanal de un grupo. No guarda el PDF, solo su resultado.';
COMMENT ON TABLE ENVIO_REPORTE_DESTINATARIO IS 'Resultado del envío del reporte semanal a cada destinatario del grupo (foto de destinatarios al crear el envío).';
