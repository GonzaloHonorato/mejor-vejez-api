-- V8__fk_compuestas_detalle_plan.sql
-- Integridad referencial por adulto mayor y grupo entre plan, detalle,
-- tarea, ocurrencia y alerta (observación del docente, entrega S4): una
-- tarea, ocurrencia o alerta no puede apuntar al detalle de un plan o a
-- una tarea de otro adulto mayor o de otro grupo.
--
-- Script de integridad del equipo, sin los comandos de SQL*Plus (PROMPT,
-- SET DEFINE y el SELECT de verificación), que Flyway no ejecuta.
--
-- Campos nuevos: DETALLE_PLAN.ID_ADULTO_MAYOR e ID_GRUPO, copiados desde
-- su PLAN_MEDICAMENTOS. La API los completa al crear el detalle.
-- Se agregan 3 UNIQUE compuestas (destino de las FK) y se sustituyen 6 FK
-- simples por 6 FK compuestas. En las FK cuyo identificador es opcional
-- (ID_TAREA, ID_DETALLE_PLAN nulos), Oracle no las comprueba; cuando la
-- referencia existe, exige que coincidan el adulto mayor y el grupo.
--
-- Aplica limpio sobre V1–V7 sin editarlas.
-- =====================================================================

-- ETAPA 1 - Agregar campos a DETALLE_PLAN
ALTER TABLE DETALLE_PLAN ADD (
    ID_ADULTO_MAYOR NUMBER,
    ID_GRUPO        NUMBER
);

-- ETAPA 2 - Completar los campos desde PLAN_MEDICAMENTOS
UPDATE DETALLE_PLAN DP
   SET (ID_ADULTO_MAYOR, ID_GRUPO) = (
       SELECT PM.ID_ADULTO_MAYOR, PM.ID_GRUPO
         FROM PLAN_MEDICAMENTOS PM
        WHERE PM.ID_PLAN = DP.ID_PLAN
   );

COMMIT;

-- ETAPA 3 - Hacer obligatorios los campos
ALTER TABLE DETALLE_PLAN MODIFY (
    ID_ADULTO_MAYOR NOT NULL,
    ID_GRUPO        NOT NULL
);

-- ETAPA 4 - Crear claves únicas compuestas
ALTER TABLE PLAN_MEDICAMENTOS
    ADD CONSTRAINT UQ_PLAN_ADULTO_GRUPO
    UNIQUE (ID_PLAN, ID_ADULTO_MAYOR, ID_GRUPO);

ALTER TABLE TAREA_CUIDADO
    ADD CONSTRAINT UQ_TAREA_ADULTO_GRUPO
    UNIQUE (ID_TAREA, ID_ADULTO_MAYOR, ID_GRUPO);

ALTER TABLE DETALLE_PLAN
    ADD CONSTRAINT UQ_DETALLE_ADULTO_GRUPO
    UNIQUE (ID_DETALLE_PLAN, ID_ADULTO_MAYOR, ID_GRUPO);

-- ETAPA 5 - DETALLE_PLAN: FK compuesta hacia PLAN_MEDICAMENTOS
ALTER TABLE DETALLE_PLAN DROP CONSTRAINT FK_DETALLE_PLAN;

ALTER TABLE DETALLE_PLAN
    ADD CONSTRAINT FK_DETALLE_PLAN_ADULTO
    FOREIGN KEY (ID_PLAN, ID_ADULTO_MAYOR, ID_GRUPO)
    REFERENCES PLAN_MEDICAMENTOS (ID_PLAN, ID_ADULTO_MAYOR, ID_GRUPO);

-- ETAPA 6 - TAREA_CUIDADO: FK compuesta hacia DETALLE_PLAN
ALTER TABLE TAREA_CUIDADO DROP CONSTRAINT FK_TAREA_DETALLE_PLAN;

ALTER TABLE TAREA_CUIDADO
    ADD CONSTRAINT FK_TAREA_DETALLE_ADULTO
    FOREIGN KEY (ID_DETALLE_PLAN, ID_ADULTO_MAYOR, ID_GRUPO)
    REFERENCES DETALLE_PLAN (ID_DETALLE_PLAN, ID_ADULTO_MAYOR, ID_GRUPO);

-- ETAPA 7 - OCURRENCIA_PLANIFICADA: FK compuestas hacia detalle y tarea
ALTER TABLE OCURRENCIA_PLANIFICADA DROP CONSTRAINT FK_OCURRENCIA_DETALLE;

ALTER TABLE OCURRENCIA_PLANIFICADA
    ADD CONSTRAINT FK_OCURRENCIA_DETALLE_ADULTO
    FOREIGN KEY (ID_DETALLE_PLAN, ID_ADULTO_MAYOR, ID_GRUPO)
    REFERENCES DETALLE_PLAN (ID_DETALLE_PLAN, ID_ADULTO_MAYOR, ID_GRUPO);

ALTER TABLE OCURRENCIA_PLANIFICADA DROP CONSTRAINT FK_OCURRENCIA_TAREA;

ALTER TABLE OCURRENCIA_PLANIFICADA
    ADD CONSTRAINT FK_OCURRENCIA_TAREA_ADULTO
    FOREIGN KEY (ID_TAREA, ID_ADULTO_MAYOR, ID_GRUPO)
    REFERENCES TAREA_CUIDADO (ID_TAREA, ID_ADULTO_MAYOR, ID_GRUPO);

-- ETAPA 8 - ALERTA_CUIDADO: FK compuestas hacia tarea y detalle
ALTER TABLE ALERTA_CUIDADO DROP CONSTRAINT FK_ALERTA_TAREA;

ALTER TABLE ALERTA_CUIDADO
    ADD CONSTRAINT FK_ALERTA_TAREA_ADULTO
    FOREIGN KEY (ID_TAREA, ID_ADULTO_MAYOR, ID_GRUPO)
    REFERENCES TAREA_CUIDADO (ID_TAREA, ID_ADULTO_MAYOR, ID_GRUPO);

ALTER TABLE ALERTA_CUIDADO DROP CONSTRAINT FK_ALERTA_DETALLE_PLAN;

ALTER TABLE ALERTA_CUIDADO
    ADD CONSTRAINT FK_ALERTA_DETALLE_ADULTO
    FOREIGN KEY (ID_DETALLE_PLAN, ID_ADULTO_MAYOR, ID_GRUPO)
    REFERENCES DETALLE_PLAN (ID_DETALLE_PLAN, ID_ADULTO_MAYOR, ID_GRUPO);
