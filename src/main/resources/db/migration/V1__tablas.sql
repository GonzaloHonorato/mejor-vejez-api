-- V1__tablas.sql
-- Mejor Vejez · Sistema de Cuidado y Monitoreo de Adultos Mayores (MVP)
-- Oracle · un solo esquema. Migración Flyway (origen: database/01_tablas.sql).
--
-- Crea las 27 tablas del modelo corregido (base SQL v11 + correcciones
-- INC-01..INC-21 del documento "Modelo de datos MVP — versión corregida").
--
-- No elimina nada: Flyway la aplica una sola vez sobre un esquema limpio.
-- Para volver a un esquema vacío en desarrollo: database/reiniciar_esquema.sql.
--
-- Convenciones:
--   * Instantes reales: TIMESTAMP WITH TIME ZONE. Fechas calendario: DATE.
--   * Horas de administración: TIMESTAMP sin zona (hora de reloj
--     America/Santiago) con la fecha fija 1970-01-01.
--   * Banderas: CHAR(1) 'S'/'N'.
--   * Estados: ID_ESTADO → CATALOGO_ESTADOS. El backend valida que el estado
--     corresponda a la tabla/campo (INC-14).
-- =====================================================================

-- =====================================================================
-- Catálogos
-- =====================================================================

CREATE TABLE CATALOGO_ESTADOS (
  ID_ESTADO      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE_TABLA   VARCHAR2(60)  NOT NULL,
  NOMBRE_CAMPO   VARCHAR2(60)  NOT NULL,
  CODIGO_ESTADO  VARCHAR2(30)  NOT NULL,
  DESCRIPCION    VARCHAR2(250) NOT NULL,
  ACTIVO         CHAR(1) DEFAULT 'S' NOT NULL,
  ORDEN          NUMBER(4) DEFAULT 1 NOT NULL,
  CONSTRAINT UQ_CAT_ESTADO_DOMINIO UNIQUE (NOMBRE_TABLA, NOMBRE_CAMPO, CODIGO_ESTADO),
  CONSTRAINT CK_CAT_ESTADO_ACTIVO CHECK (ACTIVO IN ('S','N'))
);

CREATE TABLE CATALOGO_NEGOCIO (
  ID_OPCION      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TIPO_CATALOGO  VARCHAR2(50)  NOT NULL,
  CODIGO         VARCHAR2(50)  NOT NULL,
  DESCRIPCION    VARCHAR2(160) NOT NULL,
  ACTIVO         CHAR(1) DEFAULT 'S' NOT NULL,
  ORDEN          NUMBER(4) DEFAULT 1 NOT NULL,
  CONSTRAINT UQ_OPCION_TIPO_CODIGO UNIQUE (TIPO_CATALOGO, CODIGO),
  CONSTRAINT CK_OPCION_TIPO CHECK (TIPO_CATALOGO IN ('PRESENTACION_MEDICAMENTO','UNIDAD_DOSIS','DIA_SEMANA')),
  CONSTRAINT CK_OPCION_ACTIVO CHECK (ACTIVO IN ('S','N'))
);

-- INC-19: catálogo GLOBAL de medicamentos. La unicidad normalizada
-- (UX_MEDICAMENTO_NORMALIZADO) se crea en V3__indices_y_triggers.sql.
CREATE TABLE MEDICAMENTO (
  ID_MEDICAMENTO    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE            VARCHAR2(180) NOT NULL,
  PRINCIPIO_ACTIVO  VARCHAR2(180),
  ID_PRESENTACION   NUMBER,
