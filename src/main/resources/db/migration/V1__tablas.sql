-- INC-03: única fuente del horario. Una fila por hora de administración.
-- TIMESTAMP sin zona a propósito: es la hora de reloj en America/Santiago;
-- el generador combina fecha + hora en esa zona para crear la tarea.
CREATE TABLE DETALLE_PLAN_HORARIO (
  ID_DETALLE_PLAN      NUMBER NOT NULL,
  HORA_ADMINISTRACION  TIMESTAMP NOT NULL,
  CONSTRAINT PK_DETALLE_PLAN_HORARIO PRIMARY KEY (ID_DETALLE_PLAN, HORA_ADMINISTRACION),
  CONSTRAINT FK_PLAN_HORARIO_DETALLE FOREIGN KEY (ID_DETALLE_PLAN) REFERENCES DETALLE_PLAN(ID_DETALLE_PLAN),
  CONSTRAINT CK_PLAN_HORARIO_SOLO_HORA CHECK (
    TRUNC(HORA_ADMINISTRACION) = DATE '1970-01-01'
    AND EXTRACT(SECOND FROM HORA_ADMINISTRACION) = 0
  )
);

