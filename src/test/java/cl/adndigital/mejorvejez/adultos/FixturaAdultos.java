package cl.adndigital.mejorvejez.adultos;

import java.sql.PreparedStatement;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;

/**
 * Crea adultos mayores y contactos de emergencia con {@link JdbcTemplate}
 * para pruebas de integración contra el Oracle compartido, con el mismo
 * estilo que {@code grupos.FixturaGrupos}: cada fila queda confirmada en la
 * base compartida, así que las pruebas deben filtrar siempre por sus propios
 * IDs y nunca contar tablas completas.
 */
public class FixturaAdultos {

    private final JdbcTemplate jdbcTemplate;

    public FixturaAdultos(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    /** Crea un ADULTO_MAYOR del grupo y creador indicados, en el estado dado ({@code ACTIVO} | {@code INACTIVO}). */
    public long crearAdulto(long idGrupo, long idCreador, String estado) {
        return insertarYObtenerId(
                "INSERT INTO ADULTO_MAYOR (ID_GRUPO, NOMBRE_COMPLETO, ID_ESTADO, ID_USUARIO_CREADOR) "
                        + "VALUES (?, ?, ?, ?)",
                "ID_ADULTO_MAYOR",
                idGrupo, "Adulto fixtura", idEstado("ADULTO_MAYOR", estado), idCreador);
    }

    /**
     * Crea un CONTACTO_EMERGENCIA del adulto indicado, con la designación de
     * principal y el estado dados ({@code ACTIVO} | {@code INACTIVO}).
     */
    public long crearContacto(long idAdulto, long idCreador, boolean principal, String estado) {
        return insertarYObtenerId(
                "INSERT INTO CONTACTO_EMERGENCIA "
                        + "(ID_ADULTO_MAYOR, NOMBRE_CONTACTO, TELEFONO, ES_PRINCIPAL, ID_ESTADO, ID_USUARIO_CREADOR) "
                        + "VALUES (?, ?, ?, ?, ?, ?)",
                "ID_CONTACTO",
                idAdulto, "Contacto fixtura", "+56900000000", principal ? "S" : "N",
                idEstado("CONTACTO_EMERGENCIA", estado), idCreador);
    }

    /**
     * Crea un CONTACTO_EMERGENCIA con {@code idContacto} explícito (la
     * columna es {@code GENERATED BY DEFAULT AS IDENTITY}, así que Oracle
     * acepta el valor dado). Sirve para probar comparaciones con ids por
     * sobre el rango cacheado de {@code Long} (> 127), donde {@code ==} entre
     * dos {@code Long} compara referencias en vez de valores.
     */
    public long crearContactoConId(long idContacto, long idAdulto, long idCreador, boolean principal,
            String estado) {
        jdbcTemplate.update(
                "INSERT INTO CONTACTO_EMERGENCIA "
                        + "(ID_CONTACTO, ID_ADULTO_MAYOR, NOMBRE_CONTACTO, TELEFONO, ES_PRINCIPAL, ID_ESTADO, "
                        + "ID_USUARIO_CREADOR) VALUES (?, ?, ?, ?, ?, ?, ?)",
                idContacto, idAdulto, "Contacto fixtura", "+56900000000", principal ? "S" : "N",
                idEstado("CONTACTO_EMERGENCIA", estado), idCreador);
        return idContacto;
    }

    private long idEstado(String tabla, String codigo) {
        return jdbcTemplate.queryForObject(
                "SELECT ID_ESTADO FROM CATALOGO_ESTADOS "
                        + "WHERE NOMBRE_TABLA = ? AND NOMBRE_CAMPO = 'ESTADO' AND CODIGO_ESTADO = ?",
                Long.class, tabla, codigo);
    }

    private long insertarYObtenerId(String sql, String columnaId, Object... parametros) {
        KeyHolder generadorDeClave = new GeneratedKeyHolder();
        jdbcTemplate.update(conexion -> {
            PreparedStatement sentencia = conexion.prepareStatement(sql, new String[] { columnaId });
            for (int i = 0; i < parametros.length; i++) {
                sentencia.setObject(i + 1, parametros[i]);
            }
            return sentencia;
        }, generadorDeClave);
        return generadorDeClave.getKey().longValue();
    }
}
